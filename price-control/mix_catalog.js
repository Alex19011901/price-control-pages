function classify(name){
  const n=norm(name);
  const found=PRODUCTS.filter(p=>p.re.test(n)&&!(p.exclude&&p.exclude.test(n)));
  if(found.length>1)throw new Error('MIX_AMBIGUOUS_PRODUCT: '+name+' => '+found.map(p=>p.id).join(','));
  return found[0]||null;
}
